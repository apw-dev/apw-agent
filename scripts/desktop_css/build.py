#!/usr/bin/env python3
"""Compile the Tailwind CSS used by the APW Desktop UI into internal/desktop/ui_css.go.

The Desktop page holds the API token, so it must not load remote code (no CDN).
Run this after changing class names in internal/desktop/ui.go:

    python scripts/desktop_css/build.py

Requires Node.js (npx). Tailwind is pinned to 3.4.17.
"""
import json
import pathlib
import re
import shutil
import subprocess
import sys

TAILWIND = "tailwindcss@3.4.17"
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
OUT = ROOT / "internal" / "desktop" / "ui_css.go"


def go_string_literal(s: str) -> str:
    # A JSON string is also a valid Go interpreted string literal when
    # non-ASCII is emitted as UTF-8 (ensure_ascii=False): the escapes JSON
    # produces (\" \\ \n \r \t \b \f \u00XX) are all accepted by Go.
    return json.dumps(s, ensure_ascii=False)


def main() -> int:
    npx = shutil.which("npx") or shutil.which("npx.cmd")
    if not npx:
        print("npx not found; install Node.js", file=sys.stderr)
        return 1
    cmd = [
        npx, "--yes", TAILWIND,
        "-c", str(HERE / "tailwind.config.js"),
        "-i", str(HERE / "input.css"),
        "--minify",
    ]
    proc = subprocess.run(cmd, cwd=HERE, capture_output=True, text=True, encoding="utf-8")
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        return proc.returncode
    # Drop the "/*! tailwindcss ... https://tailwindcss.com */" banner: the page
    # must not contain any URL, and the banner is useless at runtime.
    css = re.sub(r"/\*!.*?\*/", "", proc.stdout, flags=re.S).strip()
    if not css:
        print("tailwind produced no CSS", file=sys.stderr)
        sys.stderr.write(proc.stderr)
        return 1
    if "__APW_TOKEN__" in css:
        print("generated CSS must not contain the token placeholder", file=sys.stderr)
        return 1
    body = (
        "// Code generated by scripts/desktop_css/build.py; DO NOT EDIT.\n\n"
        "package desktop\n\n"
        "const desktopCSS = " + go_string_literal(css) + "\n"
    )
    OUT.write_bytes(body.encode("utf-8"))  # LF endings, UTF-8
    print(f"wrote {OUT} ({len(css)} bytes of CSS)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
